"""Compute every number the paper text uses and write paper/numbers.tex (LaTeX macros).

python -m agentipc.paper_numbers
Sections whose runs are not finished yet are skipped and reported, so the paper still builds.
"""
from __future__ import annotations

import gzip
import json
from pathlib import Path

import numpy as np
import yaml

from .analyze import analyze, load_rows
from .stats import ci

ROOT = Path(__file__).resolve().parents[2]
CH = ("A1", "A1zc", "A2", "B", "C", "D")
NAME = {"A1": "AOne", "A1zc": "AZc", "A2": "ATwo", "B": "B", "C": "C", "D": "D"}


class Macros:
    def __init__(self):
        self.lines, self.missing = [], []

    def add(self, name: str, value, fmt: str = "{}") -> None:
        self.lines.append(f"\\newcommand{{\\n{name}}}{{{fmt.format(value)}\\xspace}}")

    def write(self, path: Path) -> None:
        path.write_text("% Generated by python -m agentipc.paper_numbers; do not edit.\n" + "\n".join(self.lines) + "\n")


def latest(exp: str) -> Path | None:
    runs = sorted(p.parent for p in (ROOT / "results" / exp).glob("2*/summary.json"))
    return runs[-1] if runs else None


def pct(x: float) -> str:
    return f"{x * 100:.1f}"


def ktok(x: float) -> str:
    return f"{x / 1000:.1f}k"


def raw_records(run: Path):
    cfg = yaml.safe_load((run / "config.yaml").read_text())
    return map(json.loads, gzip.open(ROOT / "results_raw" / cfg["exp"] / run.name / "records.jsonl.gz", "rt"))


def main_run(m: Macros) -> None:
    run = latest("t07_main")
    cfg = yaml.safe_load((run / "config.yaml").read_text())
    rows = load_rows(run)
    m.add("MainTasks", cfg["n_tasks"])
    m.add("MainRuns", len(rows))
    pool = lambda ch, k, met: ci([r[met] for r in rows if r["channel"] == ch and r["k"] == k and met in r])[0]
    for ch in CH:
        n = NAME[ch]
        m.add(f"Acc{n}", pct(pool(ch, 3, "acc")))
        m.add(f"Sent{n}", ktok(pool(ch, 3, "total_tokens")))
        m.add(f"Comp{n}", ktok(pool(ch, 3, "prefill_tokens")))
        m.add(f"Notes{n}", f"{pool(ch, 3, 'judge_recall_notes') * 100:.0f}")
        m.add(f"Deliv{n}", f"{pool(ch, 3, 'judge_kept_writer_input') * 100:.0f}")
        m.add(f"Calls{n}", f"{pool(ch, 3, 'llm_calls'):.1f}")
    a1c, zc = pool("A1", 3, "prefill_tokens"), pool("A1zc", 3, "prefill_tokens")
    m.add("ZcCut", f"{(1 - zc / a1c) * 100:.0f}")
    for ch in ("B", "C", "D", "A2"):
        m.add(f"SentRatio{NAME[ch]}", f"{pool(ch, 3, 'total_tokens') / pool('A1', 3, 'total_tokens'):.1f}")
        m.add(f"CompRatio{NAME[ch]}", f"{pool(ch, 3, 'prefill_tokens') / pool('A1', 3, 'prefill_tokens'):.2f}")

    # Paired accuracy gaps to A1 over the six (dataset, k) cells.
    res = analyze(rows, "A1")
    for ch in ("A1zc", "A2", "B", "C", "D"):
        diffs = [g["acc_diff"][0] for key, g in res.items() if key.endswith(f"|{ch}") and "acc_diff" in g]
        sig = [g["acc_diff"] for key, g in res.items() if key.endswith(f"|{ch}") and "acc_diff" in g]
        n_sig = sum(1 for d in sig if d[2] < 0)
        m.add(f"Gap{NAME[ch]}Min", f"{-max(diffs) * 100:.0f}")
        m.add(f"Gap{NAME[ch]}Max", f"{-min(diffs) * 100:.0f}")
        m.add(f"Gap{NAME[ch]}Sig", n_sig)
    zc_ratio = [g["prefill_tokens"] / res[key.replace("A1zc", "A1")]["prefill_tokens"]
                for key, g in res.items() if key.endswith("|A1zc")]
    m.add("ZcRatioMin", f"{min(zc_ratio) * 100:.0f}")
    m.add("ZcRatioMax", f"{max(zc_ratio) * 100:.0f}")
    sent_ratio = {ch: [g["total_tokens"] / res[key.rsplit("|", 1)[0] + "|A1"]["total_tokens"]
                       for key, g in res.items() if key.endswith(f"|{ch}")] for ch in ("B", "C")}
    m.add("FileSentMin", f"{min(min(v) for v in sent_ratio.values()):.1f}")
    m.add("FileSentMax", f"{max(max(v) for v in sent_ratio.values()):.1f}")
    broke = {key: g["q_reviewer_broke"] for key, g in res.items() if key.endswith("|A2")}
    m.add("PipeBrokeMax", f"{max(broke.values()) * 100:.0f}")
    m.add("PipeBrokeAOne", f"{max(g['q_reviewer_broke'] for key, g in res.items() if key.endswith('|A1')) * 100:.0f}")
    deliv = {ch: [g["judge_kept_writer_input"] for key, g in res.items() if key.endswith(f"|{ch}")] for ch in ("B", "C", "D")}
    for ch, v in deliv.items():
        m.add(f"Deliv{NAME[ch]}Min", f"{min(v) * 100:.0f}")
        m.add(f"Deliv{NAME[ch]}Max", f"{max(v) * 100:.0f}")

    # Note length by channel and run-to-run nondeterminism from identical Researcher prompts.
    notes, same, pairs = {ch: [] for ch in CH}, 0, 0
    doc_reads, all_reads, no_notes, runs_fc = ({"B": 0, "C": 0} for _ in range(4))
    by_task: dict[str, dict[str, str]] = {}
    for rec in raw_records(run):
        if "error" in rec:
            continue
        if rec["k"] == 3:
            notes[rec["channel"]].append(len(rec["stage"]["notes"]))
        by_task.setdefault(rec["task_id"], {})[rec["channel"]] = rec["agents"]["researcher"]["reply"]
        if rec["k"] == 3 and rec["channel"] in ("B", "C"):
            reads = [o["path"] for o in rec["io_ops"] if o["agent"] == "writer" and o["op"] == "read" and "error" not in o]
            doc_reads[rec["channel"]] += sum(r.startswith("docs/") for r in reads)
            all_reads[rec["channel"]] += len(reads)
            no_notes[rec["channel"]] += not any(not r.startswith("docs/") for r in reads)
            runs_fc[rec["channel"]] += 1
    for t, d in by_task.items():
        if "A1" in d and "A2" in d:
            pairs += 1
            same += d["A1"] == d["A2"]
    msg = np.mean(notes["A1"] + notes["A2"])
    files = np.mean(notes["B"] + notes["C"])
    m.add("NotesCharsMsg", f"{msg:,.0f}")
    m.add("NotesCharsFile", f"{files:,.0f}")
    m.add("NotesShorter", f"{(1 - files / msg) * 100:.0f}")
    m.add("SamePrompt", f"{same / pairs * 100:.0f}")
    for ch in ("B", "C"):
        m.add(f"DocReads{ch}", f"{doc_reads[ch] / all_reads[ch] * 100:.0f}")
        m.add(f"NoNotes{ch}", f"{no_notes[ch] / runs_fc[ch] * 100:.0f}")


def setup(m: Macros) -> None:
    from .data import load_2wiki, load_hotpot, usable
    hq = load_hotpot(ROOT / "data/raw/hotpot_distractor_validation.parquet")
    wq = load_2wiki(ROOT / "data/raw/2wiki_dev.json")
    m.add("HotpotUsable", f"{sum(usable(q) for q in hq):,}")
    m.add("WikiUsable", f"{sum(usable(q) for q in wq):,}")
    env = json.loads((latest("t07_main") / "env.json").read_text())
    m.add("MaxLen", f"{env['max_model_len']:,}")


SECTIONS = [main_run, setup]


def main() -> int:
    m = Macros()
    for fn in SECTIONS:
        try:
            fn(m)
        except Exception as e:  # a section whose runs are missing is reported, not fatal
            print(f"skipped {fn.__name__}: {type(e).__name__}: {e}")
    out = ROOT / "paper" / "numbers.tex"
    m.write(out)
    print(f"wrote {len(m.lines)} macros to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
